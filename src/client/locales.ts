export type LocaleKey = keyof typeof en
export type LocaleDictionary = Record<LocaleKey, string>

export const localeKeys = Object.freeze(Object.keys(en) as LocaleKey[])

export function localeParity(): boolean {
  const english = new Set(localeKeys)
  const chinese = Object.keys(zh)
  return chinese.length === english.size && chinese.every(key => english.has(key as LocaleKey))
}
