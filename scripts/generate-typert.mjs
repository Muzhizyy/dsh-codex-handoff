import { access, copyFile, cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import { isAbsolute, resolve } from 'node:path'
import { dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { promisify } from 'node:util'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..')
const distRoot = resolve(repoRoot, 'dist')
const generatedRoot = resolve(repoRoot, 'packages', 'codex-handoff', 'generated')
const configured = process.env.DSH_TYPERT_ARTIFACT_ROOT?.trim()
export const names = ['remote.d.ts', 'remote.js', 'typert.d.ts', 'typert.js', 'typert.remote-client.d.ts.map']
const execFileAsync = promisify(execFile)
export const PINNED_SHA = 'd347e703908d0406b7a7ef80e3a0e594d86b2215'

async function stageArtifacts(artifactRoot, requireOfficialHeader) {
  for (const name of names) {
    const artifactPath = resolve(artifactRoot, name)
    try {
      const info = await stat(artifactPath)
      if (!info.isFile() || info.size === 0) throw new Error('not a non-empty file')
      await access(artifactPath)
      const contents = (await readFile(artifactPath, 'utf8')).trim()
      if (contents.length === 0 || contents === 'export {}' || contents === 'export {};') throw new Error('empty descriptor artifact')
      if (requireOfficialHeader && name !== 'typert.remote-client.d.ts.map' && !contents.startsWith('/* Generated by @deepseek-ai/dsh-typert-generator')) {
        throw new Error('artifact is not emitted by the official Typert generator')
      }
      await copyFile(artifactPath, resolve(distRoot, name))
    } catch {
      throw new Error(`Official Typert artifacts are missing or invalid: ${artifactPath}. Set DSH_PINNED_CHECKOUT to the exact upstream checkout when regenerating.`)
    }
  }
  process.stdout.write(`Typert artifacts staged from ${artifactRoot}\n`)
}

export async function generateOfficialArtifacts(checkout, artifactRoot = generatedRoot) {
  const sourceRoot = resolve(repoRoot, 'packages', 'codex-handoff')
  const targetRoot = resolve(checkout, 'packages', 'codex-handoff')
  const targetAggregate = resolve(checkout, 'tsconfig.host.json')
  const sourceAggregate = await readFile(targetAggregate, 'utf8')
  const reference = '{ "path": "./packages/codex-handoff/tsconfig.host.json" }'
  if (sourceAggregate.includes(reference)) throw new Error('pinned checkout already contains the codex-handoff contributor')
  const { stdout } = await execFileAsync(process.platform === 'win32' ? 'git.exe' : 'git', ['-C', checkout, 'rev-parse', 'HEAD'], { windowsHide: true })
  if (stdout.trim().toLowerCase() !== PINNED_SHA) throw new Error(`DSH_PINNED_CHECKOUT must be ${PINNED_SHA}`)
  await cp(sourceRoot, targetRoot, { recursive: true, errorOnExist: true })
  await writeFile(targetAggregate, sourceAggregate.replace('"references": [', `"references": [\n    ${reference},`), 'utf8')
  try {
    const generatorPath = resolve(checkout, 'packages', 'typert', 'generator', 'lib', 'index.js')
    const { WorkspaceTypertGenerator } = await import(pathToFileURL(generatorPath).href)
    const generator = new WorkspaceTypertGenerator(checkout, { checkDiagnostics: true })
    const discovered = generator.discover(['host'])
    if (!discovered.some(item => item.package === 'dsh-threadbridge')) {
      throw new Error('official Typert generator did not discover dsh-threadbridge')
    }
    const [artifact] = generator.generate(['dsh-threadbridge'], ['host'])
    if (artifact === undefined || artifact.remote === undefined) throw new Error('official Typert generator emitted no Host Remote artifact')
    await mkdir(artifactRoot, { recursive: true })
    await writeFile(resolve(artifactRoot, 'typert.js'), artifact.js, 'utf8')
    await writeFile(resolve(artifactRoot, 'typert.d.ts'), artifact.dts, 'utf8')
    await writeFile(resolve(artifactRoot, 'remote.js'), artifact.remote.js, 'utf8')
    await writeFile(resolve(artifactRoot, 'remote.d.ts'), artifact.remote.dts, 'utf8')
    await writeFile(resolve(artifactRoot, 'typert.remote-client.d.ts.map'), artifact.remote.dtsMap, 'utf8')
    process.stdout.write('Typert artifacts emitted by the pinned official WorkspaceTypertGenerator\n')
  } finally {
    await writeFile(targetAggregate, sourceAggregate, 'utf8')
    await rm(targetRoot, { recursive: true, force: true })
  }
}

async function main() {
  await mkdir(distRoot, { recursive: true })
  if (configured !== undefined && configured !== '') {
    await stageArtifacts(isAbsolute(configured) ? resolve(configured) : resolve(repoRoot, configured), false)
    return
  }
  const pinnedCheckout = process.env.DSH_PINNED_CHECKOUT?.trim()
  if (pinnedCheckout !== undefined && pinnedCheckout !== '') {
    await generateOfficialArtifacts(resolve(pinnedCheckout))
  }
  await stageArtifacts(generatedRoot, true)
}

const entry = process.argv[1] === undefined ? '' : resolve(process.argv[1])
if (entry === resolve(fileURLToPath(import.meta.url))) await main()
